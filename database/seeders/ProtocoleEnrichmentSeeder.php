            $maladie = DB::table('maladies')->where('nom', $nomMaladie)->first();

            if (!$maladie) {
                // Essayer avec LIKE en remplaçant tirets et apostrophes spéciaux
                $pattern = '%' . str_replace(['(', ')'], ['%', '%'], $nomMaladie) . '%';
                $maladie = DB::table('maladies')->where('nom', 'LIKE', $pattern)->first();
